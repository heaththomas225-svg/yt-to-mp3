// Writes cross/Purphex.Desktop/Purphex.Desktop.csproj: every file of the Windows build (the SRC list in _env.sh) compiled as one app,
// the same way the Windows build does it, so the studio window's partial classes stay in one assembly. Run after adding a file to SRC.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const env = fs.readFileSync(path.join(root, '_env.sh'), 'utf8');
const m = env.match(/SRC="([^"]+)"/); if (!m) throw new Error('no SRC= in _env.sh');
const files = m[1].split(/\s+/).filter(Boolean);
const items = files.map(f => `    <Compile Include="../../${f}" />`).join('\n');
// the same embedded files as the Windows build (the logo, the editors' pages), except the Windows web view parts
const res = [['logo.png', 'Purphex.logo.png']];
for (const r of env.matchAll(/-resource:([^, ]+),([^ "]+)/g)) if (!r[1].startsWith('wv2/') && r[1] !== 'logo.png') res.push([r[1], r[2]]);
const resItems = res.map(([f, n]) => `    <EmbeddedResource Include="../../${f}" LogicalName="${n}" />`).join('\n');
const proj = `<Project Sdk="Microsoft.NET.Sdk">
  <!-- Purphex desktop for macOS and Linux: the same files as the Windows build, on Purphex.Gfx (drawing), Avalonia (windows) and SDL (sound).
       Generated by cross/tools/desktopproj.js from the Windows file list. -->
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <OutputType>Exe</OutputType>
    <AssemblyName>Purphex</AssemblyName>
    <RootNamespace>Purphex</RootNamespace>
    <Nullable>disable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <LangVersion>latest</LangVersion>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
    <NoWarn>CS0162;CS0168;CS0169;CS0219;CS0414;CS0649;CS0618;CS0612;CS1998;CA1416;SYSLIB0011;SYSLIB0014;CS8981;CS0108;CS0114;CS0436;CS0067</NoWarn>
    <DefineConstants>$(DefineConstants);PURPHEX_DESKTOP</DefineConstants>
  </PropertyGroup>
  <ItemGroup>
    <ProjectReference Include="../Purphex.Gfx/Purphex.Gfx.csproj" />
    <PackageReference Include="Avalonia" Version="11.1.3" />
    <PackageReference Include="Avalonia.Desktop" Version="11.1.3" />
    <PackageReference Include="Avalonia.Themes.Fluent" Version="11.1.3" />
    <PackageReference Include="Avalonia.Fonts.Inter" Version="11.1.3" />
    <PackageReference Include="Silk.NET.SDL" Version="2.21.0" />
  </ItemGroup>
  <ItemGroup>
${items}
${resItems}
    <Compile Include="../Purphex.Platform/SdlAudioOut.cs" />
    <Compile Include="Forms/*.cs" />
  </ItemGroup>
</Project>
`;
fs.writeFileSync(path.join(root, 'cross', 'Purphex.Desktop', 'Purphex.Desktop.csproj'), proj);
console.log('desktop project: ' + files.length + ' files');
